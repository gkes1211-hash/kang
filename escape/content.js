// ---------------- 문제 고르기 ----------------
export const shuffle = (arr) => {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
};
const take = (arr, n) => shuffle(arr).slice(0, n);
const g6 = (g) => Math.min(6, Math.max(1, g | 0));

function englishPuzzle(kind, grade) {
  const [w, pic, ko] = pickOne(WORDS[grade]);
  if (kind === 'spell') return { type: 'spell', word: w, pic, ko, q: `${pic} "${ko}"을(를) 영어로 써요.`, hint: `첫 글자는 "${w[0]}"예요.` };
  const others = take(WORDS[grade].filter((x) => x[0] !== w), 3);
  return {
    type: 'listen', say: w, q: '잘 듣고 알맞은 것을 골라요. 🔊', showPic: grade <= 4,
    opts: [[w, pic], ...others.map((x) => [x[0], x[1]])], a: 0, ex: `${w} = ${ko}`, hint: `"${ko}"이라는 뜻이에요.`,
  };
}

